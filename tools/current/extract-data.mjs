import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';
import { assetPath, currentSourcePath, replaceDataUris } from './assets.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const html = await readFile(currentSourcePath(), 'utf8');
const scriptMarker = html.indexOf('data-dc-script');
if (scriptMarker < 0) throw new Error('No se encontró data-dc-script en design/current/current.html.');
const scriptStart = html.indexOf('>', scriptMarker);
const classStart = html.indexOf('class Component extends DCLogic', scriptStart);
if (scriptStart < 0 || classStart < 0) throw new Error('El bloque de datos no se puede separar de class Component.');

const sourceData = html.slice(scriptStart + 1, classStart).trimEnd();
const sourceFile = ts.createSourceFile('current-data.js', sourceData, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS);
const names = sourceFile.statements
  .filter(statement => ts.isVariableStatement(statement) && (statement.declarationList.flags & ts.NodeFlags.Const) !== 0)
  .flatMap(statement => statement.declarationList.declarations.map(declaration => {
    if (!ts.isIdentifier(declaration.name)) throw new Error('Se encontró un dato Current con nombre destructurado.');
    return declaration.name.text;
  }));
if (sourceFile.parseDiagnostics.length) throw new Error(`No se pudo analizar el bloque de datos Current: ${sourceFile.parseDiagnostics[0].messageText}`);
if (!names.length) throw new Error('No se encontraron declaraciones de datos en el bloque data-dc-script.');
const data = replaceDataUris(sourceData, uri => assetPath(uri))
  .replace(/^const\s+([A-Za-z_$][\w$]*)\s*=/gm, 'export const $1 =');
const lineStart = html.slice(0, scriptStart + 1).split(/\r?\n/).length;
const lineEnd = html.slice(0, classStart).split(/\r?\n/).length;
const dataPath = path.join(root, 'src/current/data.ts');
await mkdir(path.dirname(dataPath), { recursive: true });
await writeFile(dataPath, `// @ts-nocheck\n// Generated by tools/current/extract-data.mjs from design/current/current.html lines ${lineStart}-${lineEnd}.\n${data}\n`, 'utf8');

const propsMatch = /data-props='([^']*)'/.exec(html.slice(scriptMarker, scriptStart));
if (!propsMatch) throw new Error('No se encontró data-props en el script de Current.');
const propsJson = propsMatch[1]
  .replaceAll('&quot;', '"')
  .replaceAll('&amp;', '&')
  .replaceAll('&lt;', '<')
  .replaceAll('&gt;', '>')
  .replaceAll('&#39;', "'");
const metadata = JSON.parse(propsJson);
const defaults = Object.fromEntries(Object.entries(metadata)
  .filter(([name, value]) => name !== '$preview' && value && Object.hasOwn(value, 'default'))
  .map(([name, value]) => [name, value.default]));
const props = `// Generated by tools/current/extract-data.mjs from data-props in design/current/current.html.\nexport const defaultProps = ${JSON.stringify(defaults, null, 2)} as const;\nexport type CurrentProps = { [Key in keyof typeof defaultProps]: typeof defaultProps[Key] extends string ? string : typeof defaultProps[Key] };\n`;
await writeFile(path.join(root, 'src/current/props.ts'), props, 'utf8');
console.log(`Current: ${names.length} constantes exportadas y ${Object.keys(defaults).length} props generadas.`);
